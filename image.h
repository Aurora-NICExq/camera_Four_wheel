/*********************************************************************************************************************
 * 模块：image.h — 图像流水线与元素检测器（纯逻辑层）
 *
 * 约束：本头文件及 image.c 不得包含任何 MCU / 逐飞库头文件，只允许 <stdint.h> 与 config.h。
 *       目的：使本模块可在 PC 上用 gcc 直接编译，供 test/replay.c 离线回放验证。
 *
 * 职责：每帧对 188x120 灰度图执行——
 *       二值化(Otsu) → 最长白列锚定 + 八邻域双边跟踪/补线 → 加权误差 → 曲率 → 元素检测器。
 *       输出唯一结构体 track_info_t，供 fsm.c / control.c 使用。
 *
 * 为什么检测器放在这里而不是 fsm.c：检测器是"这一帧看到了什么"（纯函数，无副作用），
 * fsm 是"连续多帧看到后决定做什么"（去抖/优先级/超时都在 fsm 的唯一 switch 里）。
 ********************************************************************************************************************/
#ifndef IMAGE_H
#define IMAGE_H

#include <stdint.h>
#include "config.h"     /* IMG_W / IMG_H / 各检测器阈值宏 */

/*-------------------------------------------------------------------------------------------------------------------
 * track_info_t — 每帧图像处理的全部输出（image.c 唯一出口）
 * 行号约定：row = 0 是图像最底行（离车最近），row 越大越远。
 *           内部访问原始图像时做 (IMG_H - 1 - row) 翻转，调用方永远用"近=0"坐标。
 *------------------------------------------------------------------------------------------------------------------*/
typedef struct
{
    /* ---- 逐行几何（仅 [0, valid_rows) 区间有效） ---- */
    uint8_t  left [IMG_H];      /* 每行左边线列号 [0, IMG_W-1]，丢线时为重建值            */
    uint8_t  right[IMG_H];      /* 每行右边线列号                                        */
    uint8_t  mid  [IMG_H];      /* 每行中线 = (left+right)/2                             */
    uint8_t  width[IMG_H];      /* 每行赛道宽度（像素）：双边有效行为实测值，否则查表重建值。
                                   环岛内单边巡线需要用"进入前"的本表快照，故必须导出。   */
    uint8_t  left_lost [IMG_H]; /* 1 = 该行左边线未搜到（重建值不可信为实测）             */
    uint8_t  right_lost[IMG_H]; /* 1 = 该行右边线未搜到                                  */

    /* ---- 帧级汇总 ---- */
    uint8_t  valid_rows;        /* 融合跟踪得到的有效前瞻行数（原算法关闭融合时=最长白列长度） */
    uint8_t  longest_col;       /* 最长白列锚点列号（只负责可靠起种，不再固定用于所有行）     */
    int16_t  error;             /* 加权转向误差，单位：像素。正 = 中线在图像中心右侧。
                                   由低速/高速两张权重表按 duty 归一化混合后加权平均。    */
    int16_t  curvature;         /* 远段与近段中线斜率差，Q8 定点（实际斜率差 x256）。
                                   |curvature| 越大前方越弯，是滑行减速表的输入之一。     */
    uint8_t  both_lost_rows;    /* 双边同时丢失的行数（十字特征输入 / 失控保护输入）      */
    uint8_t  threshold;         /* 本帧实际使用的二值化阈值（Otsu 结果或固定值）          */

    /* ---- 元素检测器原始输出（单帧判定，未去抖 —— 去抖只发生在 fsm.c） ---- */
    uint8_t  det_cross;         /* 1 = 本帧呈十字特征（连续行带双边丢失 + 上下拐点）      */
    uint8_t  det_ring_left;     /* 1 = 本帧呈左环岛特征（右边线连续、左边线圆弧+拐点）    */
    uint8_t  det_ring_right;    /* 1 = 本帧呈右环岛特征                                  */
    uint8_t  det_ramp;         /* 1 = 本帧呈坡道特征（占位实现：赛道突然变宽/地平线跳变） */
    uint8_t  inflect_row;       /* 拐点所在行号（十字/环岛共用调试与补线锚点，无则 0xFF） */
    int16_t  det_value;         /* 触发检测器的特征强度，供 FSM 转移
                                   轨迹环形缓冲记录 trigger value 用。                   */
} track_info_t;

/*-------------------------------------------------------------------------------------------------------------------
 * image_process — 图像流水线总入口，每帧调用一次
 * 输入：img       原始灰度图 [IMG_H][IMG_W]，img[0] 是图像顶行（相机原始顺序，内部翻转）
 *       duty_now  上一帧指令占空比 [0,10000]，用于低速/高速转向权重表的线性混合。
 *                 为什么前瞻要随速度增长：无编码器且只能滑行减速，速度越高，
 *                 需要越早"看见"弯道并提前打舵/切占空比，故高速权重表远移。
 * 输出：out       本帧 track_info_t（全部字段填写）
 * 说明：逐像素路径只用整数；不使用任何静态跨帧状态（宽度表为帧内学习），
 *       同一输入必然产生同一输出 —— replay 回放结果与车载完全一致。
 *------------------------------------------------------------------------------------------------------------------*/
void image_process(const uint8_t img[IMG_H][IMG_W], uint16_t duty_now, track_info_t *out);

/* 图像安全健康判定：覆盖全黑/短前瞻，以及 valid_rows 仍很高的全白/严重过曝。
 * severe=1 表示应使用 FAILSAFE_SEVERE_FRAMES 的快速断油路径。 */
uint8_t image_track_invalid(const track_info_t *ti, uint8_t *severe);

/*-------------------------------------------------------------------------------------------------------------------
 * 元素检测器 — 纯函数，无副作用，无静态状态。
 * image_process 内部会依次调用并把结果写入 track_info_t；
 * 单独导出是为了 replay 回放程序可以针对单个检测器喂帧做定向测试。
 * 输入均为已完成边线搜索的 track_info_t（几何字段有效），返回 0/1。
 *------------------------------------------------------------------------------------------------------------------*/
uint8_t detect_cross     (const track_info_t *ti);              /* 十字：行带双边丢失 + 上下拐点     */
uint8_t detect_ring_left (const track_info_t *ti);              /* 左环岛：右边连续 + 左边圆弧拐点   */
uint8_t detect_ring_right(const track_info_t *ti);              /* 右环岛：镜像                     */
uint8_t detect_ramp      (const track_info_t *ti);              /* 坡道（占位）：突然变宽/地平线跳变 */

#endif /* IMAGE_H */
