/*********************************************************************************************************************
 * 模块：motor.h — 硬件执行层：舵机 + 单路电机 PWM + 时间戳 + 按键/蜂鸣器
 *
 * 本层是唯一允许包含逐飞库头文件的执行模块（motor.c 内包含 zf_driver_pwm.h 等；
 * 本头文件本身只暴露 <stdint.h> 接口，保证上层 include 它也不会带入 MCU 头）。
 *
 * 职责边界：只做"把数值写进外设"，不做任何决策。
 *   - 舵机：写入前再次调用 control_servo_clamp() —— 第二道、也是最后一道机械限位；
 *   - 电机：单路正转 PWM，duty [0,10000] 直写（斜坡已在 control.c 完成）；
 *   - ENABLE_HW_BRAKE 为 1 时才编译刹车/使能脚控制（默认 0，任何逻辑不得依赖它）；
 *   - 板上无电池分压 ADC（已确认）→ 不提供电压接口，ENABLE_VBAT_COMP 恒为 0。
 ********************************************************************************************************************/
#ifndef MOTOR_H
#define MOTOR_H

#include <stdint.h>

/*-------------------------------------------------------------------------------------------------------------------
 * motor_hw_init — 初始化舵机 PWM（50 Hz，GTM ATOM）、电机 PWM（~17 kHz，不同 ATOM 模块）、
 *                 蜂鸣器 GPIO、按键。上电即输出 舵机中位 + 占空比 0。
 *------------------------------------------------------------------------------------------------------------------*/
void motor_hw_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * motor_apply — 每帧一次，把控制输出写入硬件
 * 输入：servo_pwm  舵机 PWM 值（内部仍强制过 control_servo_clamp，双保险）
 *       duty       电机占空比 [0,10000]，超限截断
 *------------------------------------------------------------------------------------------------------------------*/
void motor_apply(uint16_t servo_pwm, uint16_t duty);

/*-------------------------------------------------------------------------------------------------------------------
 * motor_stop — 立即占空比 0（滑行停车——本硬件唯一的"停"）。解锁前/失控保护用。
 *------------------------------------------------------------------------------------------------------------------*/
void motor_stop(void);

/*-------------------------------------------------------------------------------------------------------------------
 * hal_time_us — 系统运行微秒数（逐飞 system_getval_us()，STM 定时器）。
 * 用途：帧内流水线耗时测量（display 显示，超预算时提高 COL_STEP）。
 *------------------------------------------------------------------------------------------------------------------*/
uint32_t hal_time_us(void);

/*-------------------------------------------------------------------------------------------------------------------
 * 按键 / 蜂鸣器（薄封装：上层不触碰逐飞 key/gpio API）
 *------------------------------------------------------------------------------------------------------------------*/
uint8_t hal_key_pressed(uint8_t key_index);     /* 1 = 该键本次扫描为短按（读取即清除） */
void    hal_key_scan(void);                     /* 每帧调用一次的按键扫描               */
void    hal_buzzer_on(void);                    /* 蜂鸣器开（chirp 时长由上层帧计数控制）*/
void    hal_buzzer_off(void);

#endif /* MOTOR_H */
