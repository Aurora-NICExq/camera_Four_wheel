/*********************************************************************************************************************
 * 模块：control.h — 转向 PD + 滑行式开环速度策略（纯逻辑层）
 *
 * 约束：不包含任何 MCU / 逐飞库头文件，只允许 <stdint.h>、config.h、image.h、fsm.h。
 *       逐帧控制数学允许浮点（每帧一次，不在逐像素路径）。
 *
 * 硬件事实（决定本模块全部设计）：
 *   - 无编码器 → 没有速度闭环，输出只是占空比 [0,10000]；
 *   - 电机驱动只能正转 → 减速 = 滑行（coast），无反拖无刹车 → 所有降速决策必须
 *     依赖视觉前瞻提前触发，比"有刹车的车"早得多；
 *   - 双后轮共享一路 PWM → 无电子差速，弯中速度完全由 MIN_TURN_DUTY + 滑行决定。
 ********************************************************************************************************************/
#ifndef CONTROL_H
#define CONTROL_H

#include <stdint.h>
#include "config.h"
#include "image.h"
#include "fsm.h"

/*---- 每帧控制输出：main.c 原样转交 motor 层，逻辑层与硬件层之间唯一的"电传"接口 ----*/
typedef struct
{
    uint16_t servo_pwm;     /* 舵机 PWM 输出值（已经过机械限位钳制——本结构体内的值
                               保证安全，但 motor 层仍会再钳一次：双保险，无路径可绕过）*/
    uint16_t duty;          /* 电机占空比 [0,10000]（已过斜坡与所有上限）              */
    int16_t  error_used;    /* 本帧实际参与 PD 的误差（含契约表转向源换算），遥测用    */
    uint16_t duty_target;   /* 斜坡前的目标占空比，调试"减速表是否触发"用             */
} control_out_t;

/*-------------------------------------------------------------------------------------------------------------------
 * control_init — 上电/重新解锁时复位（prev_error、D 项滤波、斜坡当前值、加速/直道确认计数）
 *------------------------------------------------------------------------------------------------------------------*/
void control_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * control_update — 每帧调用一次（在 fsm_update 之后）
 * 输入：ti      本帧图像结果
 *       armed   0 = 未解锁/失控保护触发 → duty 强制 0（舵机仍随动，便于推车对中）
 * 输出：out     本帧舵机与占空比指令
 *
 * 转向：servo = SERVO_CENTER + Kp(|e|)*e + Kd*d_filt
 *   - Kp 随 |e| 调度（分段/二次可选，宏切换恒定 Kp）：零点附近小（高速直道稳），
 *     大误差时增大（弯道打舵权威）；
 *   - D 项防踢：fsm_state_just_entered() 为真的那一帧强制 prev_error = error（D=0），
 *     转向源跳变不得打出舵机尖峰；D 项再过 2~3 帧 EMA（像素量化导致原始差分抖动）；
 *   - 最后一步永远是机械限位钳制 [SERVO_CENTER-SERVO_RANGE, SERVO_CENTER+SERVO_RANGE]。
 *
 * 速度（全开环，滑行减速）：
 *   duty_target = min( 行数减速表(valid_rows), 曲率减速表(|curvature|),
 *                      转向减速(|servo偏角|), 契约表 duty_cap, 硬上限 )
 *   - 两张表为分段查表（非线性），是全项目最重要的整定值，锚定于 README §滑行标定；
 *   - 降斜坡默认不限（瞬间切占空比 = 开始滑行，安全）；升斜坡小步长防打滑空转；
 *   - 弯出再加速：|e| 小 且 行数回升 且 |curvature| 低，连续 EXIT_CONFIRM_FRAMES 帧
 *     → 沿升斜坡回直道占空比（出弯比极速更影响圈速）；
 *   - 长直道加速：近乎完美直道持续 BOOST_CONFIRM_FRAMES 帧 → 允许至 BOOST_DUTY，
 *     远行一见曲率立即退出（boost 上限 = 可见前瞻内能滑回弯速的速度）。
 *------------------------------------------------------------------------------------------------------------------*/
void control_update(const track_info_t *ti, uint8_t armed, control_out_t *out);

/*-------------------------------------------------------------------------------------------------------------------
 * control_servo_clamp — 最终机械限位钳制（唯一实现，motor.c 复用同一函数做第二道钳制）
 * 任何舵机命令的必经之路；独立导出以便 replay 断言"无越限输出"。
 *------------------------------------------------------------------------------------------------------------------*/
uint16_t control_servo_clamp(int32_t servo_raw);

#endif /* CONTROL_H */
