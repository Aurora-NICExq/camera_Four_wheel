#define STEER_DUTY_SLOPE_DEN    (1)

/* 占空比斜坡（每帧最大变化量）：
 * 降斜坡默认 10000 = 不限幅 —— 瞬间切占空比只是"开始滑行"，无反拖不会抱死，是安全的；保留宏做实验。
 * 升斜坡要小：单通道双电机同时上电流，猛给会打滑（无编码器测不到打滑，只能预防）。                */
