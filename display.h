/*********************************************************************************************************************
 * 模块：display.h — 预算受限的调试输出（IPS200 屏 + 逐飞无线串口）
 *
 * 硬规则：屏幕/串口写入绝不允许阻塞或拖慢帧同步主循环。
 *   - 比赛模式（DEBUG_NO_DRIVE==0）：不画图，纯文本（状态/误差/占空比/耗时），
 *     由帧计数器限流至 ≤ 2 Hz；
 *   - 调试模式（DEBUG_NO_DRIVE==1）：二值图 + 边线/中线叠加，抽点降采样、
 *     每 ~10 帧刷新一次；第 2 页 FSM 转移轨迹；按键翻页；
 *   - 串口整帧图像流仅限调试模式，且分块非阻塞发送
 *     （188x120 @115200 波特 ≈ 2 s，阻塞写必然卡死帧循环）；
 *   - FSM 状态进入时蜂鸣器短促鸣叫（不同状态不同时长，靠听辨认元素触发）。
 *
 * 本头文件只暴露 <stdint.h> + 逻辑层类型；display.c 内部才包含逐飞屏幕/串口驱动。
 ********************************************************************************************************************/
#ifndef DISPLAY_H
#define DISPLAY_H

#include <stdint.h>
#include "image.h"
#include "fsm.h"
#include "control.h"

/*-------------------------------------------------------------------------------------------------------------------
 * display_init — 屏幕 + 无线串口初始化（在 motor_hw_init 之后、相机初始化之前调用）
 *------------------------------------------------------------------------------------------------------------------*/
void display_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * display_update — 每帧调用一次；内部自行按帧计数限流，绝大多数帧立即返回
 * 输入：img       本帧原始灰度图（调试模式画二值叠加图用；比赛模式不读）
 *       ti        本帧图像结果
 *       out       本帧控制输出
 *       proc_us   本帧流水线耗时（µs），由 main.c 用 hal_time_us() 测得
 *       armed     解锁状态（屏幕状态栏显示）
 *------------------------------------------------------------------------------------------------------------------*/
void display_update(const uint8_t img[IMG_H][IMG_W], const track_info_t *ti,
                    const control_out_t *out, uint32_t proc_us, uint8_t armed);

/*-------------------------------------------------------------------------------------------------------------------
 * display_next_page — 按键翻页（0: 总览 / 1: 图像叠加(仅调试模式) / 2: FSM 轨迹）
 *------------------------------------------------------------------------------------------------------------------*/
void display_next_page(void);

/*-------------------------------------------------------------------------------------------------------------------
 * display_chirp — 请求一次蜂鸣器短鸣（FSM 状态进入时由 main.c 触发；
 *                 时长按帧计数在 display_update 内部结束，不阻塞）
 * 输入：state — 进入的状态（不同状态映射不同鸣叫帧数）
 *------------------------------------------------------------------------------------------------------------------*/
void display_chirp(fsm_state_t state);

/*-------------------------------------------------------------------------------------------------------------------
 * display_telemetry — 每帧一行遥测（ENABLE_UART_TELEMETRY 时编译；内部限流+非阻塞）
 * TEST_COAST 模式下改为每帧输出 (frame, valid_rows, duty)，供滑行特性标定。
 *------------------------------------------------------------------------------------------------------------------*/
void display_telemetry(const track_info_t *ti, const control_out_t *out, uint32_t frame);

#endif /* DISPLAY_H */
