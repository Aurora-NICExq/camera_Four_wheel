/*********************************************************************************************************************
 * 模块：display.h — 无线串口遥测 + 蜂鸣器状态提示音（不再碰屏幕）
 *
 * 屏幕归属：IPS200 现由调试菜单常驻独占（menu.c）——本模块不画屏，只做遥测与蜂鸣。
 * 硬规则：串口写入绝不允许阻塞或拖慢帧同步主循环（内部按帧计数限流、非阻塞）。
 *   - 无线串口遥测：一行文本（帧号/误差/有效行/占空比），按 TELEMETRY_DIV 限流；
 *   - 图像失效 / 相机看门狗时蜂鸣器长鸣（直道+转弯无状态机，只剩这一种提示音）。
 *
 * 本头文件只暴露 <stdint.h> + 逻辑层类型；display.c 内部才包含逐飞屏幕/串口驱动。
 ********************************************************************************************************************/
#ifndef DISPLAY_H
#define DISPLAY_H

#include <stdint.h>
#include "image.h"
#include "control.h"

/*-------------------------------------------------------------------------------------------------------------------
 * display_init — IPS200 竖屏硬件初始化（一次）+ 无线串口初始化。
 *                ips200_set_dir(IPS200_PORTAIT) 必须在 ips200_init 之前（SeekFree 库约束）。
 *                在 motor_hw_init 之后、menu_init 之前调用（menu_init 随后接管整屏）。
 *------------------------------------------------------------------------------------------------------------------*/
void display_init(void);

/*-------------------------------------------------------------------------------------------------------------------
 * display_update — 每帧调用一次；只负责蜂鸣器提示音（不碰屏幕），绝不阻塞。
 *------------------------------------------------------------------------------------------------------------------*/
void display_update(void);

/*-------------------------------------------------------------------------------------------------------------------
 * display_chirp_fault — 请求一次故障长鸣（图像失效 / 相机看门狗时由 cpu0_main 触发；
 *                       时长按帧计数在 display_update 内部结束，不阻塞）。
 *------------------------------------------------------------------------------------------------------------------*/
void display_chirp_fault(void);

/*-------------------------------------------------------------------------------------------------------------------
 * display_telemetry — 每帧一行遥测（ENABLE_UART_TELEMETRY 时编译；内部限流+非阻塞）
 * TEST_COAST 模式下改为每帧输出 (frame, valid_rows, duty)，供滑行特性标定。
 *------------------------------------------------------------------------------------------------------------------*/
void display_telemetry(const track_info_t *ti, const control_out_t *out, uint32_t frame);

#endif /* DISPLAY_H */
